"""Run all scenarios offline and write the eval table.

    python -m evals.run_evals            # writes docs/EVAL_RESULTS.md + evals/results.json
"""
from __future__ import annotations

import os
import sys
from datetime import datetime

from .harness import dump_json, run_scenario
from .scenarios import SCENARIOS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def charts(results: list) -> list[str]:
    """Mermaid charts (GitHub renders them): overall result and coverage by category."""
    passed = sum(r.passed for r in results)
    cats: dict[str, list[int]] = {}
    for r in results:
        c = cats.setdefault(r.category, [0, 0])
        c[0] += r.passed
        c[1] += 1
    out = ["```mermaid", "pie showData title Scenarios", f'    "Passed" : {passed}']
    if passed < len(results):
        out.append(f'    "Failed" : {len(results) - passed}')
    out += ["```", "", "```mermaid", "pie showData title Scenarios by category"]
    out += [f'    "{name} ({ok}/{n} pass)" : {n}' for name, (ok, n) in sorted(cats.items(), key=lambda kv: -kv[1][1])]
    out += ["```", ""]
    return out


def main(argv: list[str]) -> int:
    os.chdir(ROOT)
    os.makedirs("docs/traces", exist_ok=True)
    only = set(argv[1:])
    results = [run_scenario(s) for s in SCENARIOS if not only or s.name in only]
    passed = sum(r.passed for r in results)
    lines = [
        "# Eval results",
        "",
        f"_Generated by `python -m evals.run_evals` on {datetime.now().strftime('%Y-%m-%d %H:%M')} — "
        f"scripted model, offline, seeded. **{passed}/{len(results)} passed.**_",
        "",
        "Every scenario also runs the global invariants: no side effect without a matching approval · "
        "no duplicate bookings · context within budget and memory-gated · every run ends with a reply · "
        "no unverified success claims.",
        "",
        *charts(results),
        "| # | Scenario | Category | Expected | Actual | Result | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(results, 1):
        lines.append(f"| {i} | `{r.name}` | {r.category} | {_cell(r.expected)} | {_cell(r.actual)} | "
                     f"{'✅ pass' if r.passed else '❌ FAIL'} | {_cell(r.notes)} |")
    lines += ["", "## Per-check detail", ""]
    for r in results:
        lines.append(f"<details><summary>{'✅' if r.passed else '❌'} {r.name}</summary>\n")
        for ch in r.checks:
            lines.append(f"- {'✅' if ch['ok'] else '❌'} **{_cell(ch['check'])}** — {_cell(ch['detail'])}")
        lines.append("\n</details>\n")
    if not only:  # a filtered run must not overwrite the full table
        with open("docs/EVAL_RESULTS.md", "w") as f:
            f.write("\n".join(lines) + "\n")
        dump_json(results, "evals/results.json")
    for r in results:
        print(f"{'PASS' if r.passed else 'FAIL'}  {r.name:45s} {r.actual}")
        if not r.passed:
            print("      ", r.notes[:600])
    print(f"\n{passed}/{len(results)} passed")
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
